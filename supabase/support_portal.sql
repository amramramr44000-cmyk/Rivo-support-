-- Optional but useful: notification trigger using Rivo's existing notifications table when present.
do $$ begin
  if to_regclass('public.rivo_notifications') is not null then
    create or replace function public.rivo_support_notify() returns trigger language plpgsql security definer set search_path=public as $fn$
    declare tid public.rivo_support_tickets; receiver uuid;
    begin
      select * into tid from public.rivo_support_tickets where id=new.ticket_id;
      if tid.user_id = new.sender_id then
        receiver := tid.assigned_admin_id;
      else
        receiver := tid.user_id;
      end if;
      if receiver is not null and receiver <> new.sender_id then
        begin
          perform public.rivo_write_notification(receiver,new.sender_id,'message','رسالة جديدة في طلب الدعم',jsonb_build_object('ticket_id',new.ticket_id,'support',true));
        exception when others then null; end;
      end if;
      return new;
    end;$fn$;
    drop trigger if exists trg_rivo_support_notify on public.rivo_support_messages;
    create trigger trg_rivo_support_notify after insert on public.rivo_support_messages for each row execute function public.rivo_support_notify();
  end if;
end $$;
