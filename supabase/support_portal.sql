-- Rivo Support Portal: additive migration for the existing Rivo Supabase project.
-- Rivo login bridge: resolve the real Supabase Auth email from the Rivo username.
-- Needed because the Support Portal uses the existing Rivo username/password login.
create or replace function public.rivo_get_login_email(p_username text)
returns text
language sql
security definer
set search_path = public, auth
as $$
  select u.email
  from public.profiles p
  join auth.users u on u.id = p.id
  where lower(p.username) = lower(trim(both '@' from coalesce(p_username, '')))
  limit 1;
$$;
revoke all on function public.rivo_get_login_email(text) from public;
grant execute on function public.rivo_get_login_email(text) to anon, authenticated;

-- Does NOT modify existing Rivo tables or functions. Uses the same auth.users/profiles
-- and the existing rivo_is_admin() function.

create table if not exists public.rivo_support_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null check (char_length(trim(subject)) between 3 and 120),
  category text not null default 'other' check (category in ('account','technical','payment','report','privacy','other')),
  priority text not null default 'normal' check (priority in ('low','normal','high')),
  status text not null default 'open' check (status in ('open','pending','closed')),
  assigned_admin_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);

create index if not exists rivo_support_tickets_user_idx on public.rivo_support_tickets(user_id, updated_at desc);
create index if not exists rivo_support_tickets_status_idx on public.rivo_support_tickets(status, updated_at desc);
create index if not exists rivo_support_tickets_assigned_idx on public.rivo_support_tickets(assigned_admin_id, status, updated_at desc);

create table if not exists public.rivo_support_messages (
  id bigint generated by default as identity primary key,
  ticket_id uuid not null references public.rivo_support_tickets(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  content text not null default '' check (char_length(trim(content)) <= 4000),
  attachment_path text,
  attachment_type text,
  created_at timestamptz not null default now()
);
create index if not exists rivo_support_messages_ticket_idx on public.rivo_support_messages(ticket_id, created_at asc);

create table if not exists public.rivo_support_events (
  id bigint generated by default as identity primary key,
  ticket_id uuid not null references public.rivo_support_tickets(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists rivo_support_events_ticket_idx on public.rivo_support_events(ticket_id, created_at desc);

alter table public.rivo_support_tickets enable row level security;
alter table public.rivo_support_messages enable row level security;
alter table public.rivo_support_events enable row level security;

-- RLS is defensive; browser mutations still go through controlled RPCs.
drop policy if exists "support_ticket_customer_select" on public.rivo_support_tickets;
create policy "support_ticket_customer_select" on public.rivo_support_tickets for select to authenticated
using (user_id = auth.uid() or public.rivo_is_admin(auth.uid()));

drop policy if exists "support_message_participant_select" on public.rivo_support_messages;
create policy "support_message_participant_select" on public.rivo_support_messages for select to authenticated
using (exists (select 1 from public.rivo_support_tickets t where t.id = ticket_id and (t.user_id = auth.uid() or public.rivo_is_admin(auth.uid()))));

drop policy if exists "support_event_admin_select" on public.rivo_support_events;
create policy "support_event_admin_select" on public.rivo_support_events for select to authenticated
using (public.rivo_is_admin(auth.uid()) or exists (select 1 from public.rivo_support_tickets t where t.id = ticket_id and t.user_id = auth.uid()));

-- Private support attachments. The browser can create signed URLs only after the
-- object passes this policy. Customers access their own folder; admins can access all.
do $$ begin
  insert into storage.buckets (id, name, public)
  values ('rivo-support-media','rivo-support-media',false)
  on conflict (id) do update set public=false;
exception when undefined_table then null; end $$;

drop policy if exists "support_media_insert" on storage.objects;
create policy "support_media_insert" on storage.objects for insert to authenticated
with check (bucket_id = 'rivo-support-media' and (name like auth.uid()::text || '/%'));

drop policy if exists "support_media_select" on storage.objects;
create policy "support_media_select" on storage.objects for select to authenticated
using (bucket_id = 'rivo-support-media' and (name like auth.uid()::text || '/%' or public.rivo_is_admin(auth.uid())));

drop policy if exists "support_media_delete" on storage.objects;
create policy "support_media_delete" on storage.objects for delete to authenticated
using (bucket_id = 'rivo-support-media' and (name like auth.uid()::text || '/%' or public.rivo_is_admin(auth.uid())));

