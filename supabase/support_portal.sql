create or replace function public.rivo_support_admin_stats()
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare r jsonb;begin
  if not public.rivo_is_admin(auth.uid()) then raise exception 'Access denied'; end if;
  select jsonb_build_object('total',count(*),'open',count(*) filter(where status='open'),'pending',count(*) filter(where status='pending'),'closed',count(*) filter(where status='closed'),'unassigned',count(*) filter(where assigned_admin_id is null and status<>'closed'),'today',count(*) filter(where created_at>=date_trunc('day',now()))) into r from public.rivo_support_tickets;
  return r;
end;
$$;
revoke all on function public.rivo_support_admin_stats() from public;
