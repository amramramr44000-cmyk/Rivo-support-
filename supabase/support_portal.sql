create or replace function public.rivo_support_create_ticket(p_subject text,p_category text default 'other',p_priority text default 'normal',p_message text default '')
returns jsonb language plpgsql security definer set search_path=public as $$
declare tid uuid;
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if char_length(trim(coalesce(p_subject,''))) < 3 then raise exception 'عنوان المشكلة قصير جدًا'; end if;
  insert into public.rivo_support_tickets(user_id,subject,category,priority)
  values(auth.uid(),trim(p_subject),case when p_category in ('account','technical','payment','report','privacy','other') then p_category else 'other' end,case when p_priority in ('low','normal','high') then p_priority else 'normal' end)
  returning id into tid;
  if char_length(trim(coalesce(p_message,''))) > 0 then
    insert into public.rivo_support_messages(ticket_id,sender_id,content) values(tid,auth.uid(),trim(p_message));
    update public.rivo_support_tickets set last_message_at=now(),updated_at=now() where id=tid;
  end if;
  insert into public.rivo_support_events(ticket_id,actor_id,event_type,payload) values(tid,auth.uid(),'created',jsonb_build_object('category',p_category,'priority',p_priority));
  return jsonb_build_object('id',tid);
end;
$$;
revoke all on function public.rivo_support_create_ticket(text,text,text,text) from public;
grant execute on function public.rivo_support_create_ticket(text,text,text,text) to authenticated;

create or replace function public.rivo_support_list_tickets(p_scope text default 'mine',p_status text default 'all',p_limit int default 100,p_offset int default 0)
returns setof jsonb language sql stable security definer set search_path=public as $$
select jsonb_build_object(
  'id',t.id,'subject',t.subject,'category',t.category,'priority',t.priority,'status',t.status,
  'status_label',case t.status when 'open' then 'مفتوح' when 'pending' then 'بانتظار الرد' else 'مغلق' end,
  'priority_label',case t.priority when 'high' then 'عالية' when 'low' then 'منخفضة' else 'عادية' end,
  'username',p.username,'updated_at',t.updated_at,'assigned_admin_username',ap.username
)
from public.rivo_support_tickets t
join public.profiles p on p.id=t.user_id
left join public.profiles ap on ap.id=t.assigned_admin_id
where ((coalesce(p_scope,'mine')='mine' and t.user_id=auth.uid()) or (coalesce(p_scope,'mine')='admin' and public.rivo_is_admin(auth.uid())))
  and (coalesce(p_status,'all')='all' or t.status=p_status)
order by t.updated_at desc
limit greatest(1,least(coalesce(p_limit,100),200)) offset greatest(0,coalesce(p_offset,0));
$$;
revoke all on function public.rivo_support_list_tickets(text,text,int,int) from public;
grant execute on function public.rivo_support_list_tickets(text,text,int,int) to authenticated;

create or replace function public.rivo_support_get_ticket(p_ticket_id uuid)
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare t public.rivo_support_tickets; out jsonb; can_see boolean;begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  select * into t from public.rivo_support_tickets where id=p_ticket_id;
  if not found then raise exception 'Ticket not found'; end if;
  can_see := t.user_id=auth.uid() or public.rivo_is_admin(auth.uid());
  if not can_see then raise exception 'Access denied'; end if;
  select jsonb_build_object(
    'id',t.id,'subject',t.subject,'category',t.category,'priority',t.priority,'status',t.status,
    'status_label',case t.status when 'open' then 'مفتوح' when 'pending' then 'بانتظار الرد' else 'مغلق' end,
    'priority_label',case t.priority when 'high' then 'عالية' when 'low' then 'منخفضة' else 'عادية' end,
    'user',jsonb_build_object('id',p.id,'username',p.username,'display_name',coalesce(p.public_data->>'displayName',p.username)),
    'messages',coalesce((select jsonb_agg(jsonb_build_object('id',m.id,'sender_id',m.sender_id,'sender_name',coalesce(mp.public_data->>'displayName',mp.username),'content',m.content,'created_at',m.created_at,'attachment_path',m.attachment_path,'attachment_type',m.attachment_type) order by m.created_at asc) from public.rivo_support_messages m join public.profiles mp on mp.id=m.sender_id where m.ticket_id=t.id),'[]'::jsonb)
  ) into out
  from public.profiles p where p.id=t.user_id;
  return out;
end;
$$;
revoke all on function public.rivo_support_get_ticket(uuid) from public;
grant execute on function public.rivo_support_get_ticket(uuid) to authenticated;

create or replace function public.rivo_support_send_message(p_ticket_id uuid,p_content text default '',p_attachment_path text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare t public.rivo_support_tickets; sid uuid:=auth.uid(); mid bigint; admin boolean;begin
  if sid is null then raise exception 'Not authenticated'; end if;
  select * into t from public.rivo_support_tickets where id=p_ticket_id;
  if not found then raise exception 'Ticket not found'; end if;
  admin := public.rivo_is_admin(sid);
  if t.user_id<>sid and not admin then raise exception 'Access denied'; end if;
  if t.status='closed' then raise exception 'البلاغ مغلق. أعد فتحه قبل إرسال رسالة.'; end if;
  if char_length(trim(coalesce(p_content,'')))=0 and nullif(trim(coalesce(p_attachment_path,'')),'') is null then raise exception 'Message is empty'; end if;
  if p_attachment_path is not null and p_attachment_path <> '' and position(sid::text||'/' in p_attachment_path) <> 1 and not admin then raise exception 'Invalid attachment path'; end if;
  insert into public.rivo_support_messages(ticket_id,sender_id,content,attachment_path,attachment_type)
  values(p_ticket_id,sid,trim(coalesce(p_content,'')),nullif(trim(p_attachment_path),''),case when p_attachment_path is null then null else 'image' end)
  returning id into mid;
  update public.rivo_support_tickets set updated_at=now(),last_message_at=now(),status=case when admin then 'pending' else 'open' end where id=p_ticket_id;
  insert into public.rivo_support_events(ticket_id,actor_id,event_type,payload) values(p_ticket_id,sid,'message',jsonb_build_object('message_id',mid));
  return jsonb_build_object('id',mid);
end;
$$;
revoke all on function public.rivo_support_send_message(uuid,text,text) from public;
grant execute on function public.rivo_support_send_message(uuid,text,text) to authenticated;

create or replace function public.rivo_support_assign_ticket(p_ticket_id uuid)
returns boolean language plpgsql security definer set search_path=public as $$
begin
  if not public.rivo_is_admin(auth.uid()) then raise exception 'Access denied'; end if;
  update public.rivo_support_tickets set assigned_admin_id=auth.uid(),status=case when status='closed' then 'open' else status end,updated_at=now() where id=p_ticket_id;
  if not found then raise exception 'Ticket not found'; end if;
  insert into public.rivo_support_events(ticket_id,actor_id,event_type) values(p_ticket_id,auth.uid(),'assigned');
  return true;
end;
$$;
revoke all on function public.rivo_support_assign_ticket(uuid) from public;
grant execute on function public.rivo_support_assign_ticket(uuid) to authenticated;

